#!/usr/bin/env node
/*
 * db/first-partners.json  ->  db/seed-first-partners.sql
 *
 * The marketplace's provider rows, written as reviewable data rather than typed
 * into a console. Run it, read the SQL, then apply it once:
 *
 *   node scripts/seed-partners.js
 *   npx wrangler d1 execute serve-marketplace --remote --file db/seed-first-partners.sql
 *
 * Needs migrations 0001 AND 0002 applied first (0002 adds service_areas).
 *
 * EVERY PROVIDER IS SEEDED UNLISTED. `listed` is forced to 0 here whatever the
 * JSON says: these profiles were drafted by Serve from public websites, and a
 * company becomes public only after its owner has approved the profile and the
 * founder flips `listed` by hand. A seed must never be the thing that
 * publishes somebody.
 *
 * INSERT OR IGNORE, so re-running the file never overwrites an edit made in D1
 * since. Changing a seeded provider afterwards is an UPDATE, deliberately.
 *
 * THIS REPO IS PUBLIC, SO THE JSON HERE CARRIES NO INTERNAL FIELDS.
 * internal_phone, internal_email, website_url and internal_notes (the "confirm
 * with the owner" list) exist in the live D1 rows and in the private copy at
 * ../.agent-memory/marketplace/first-partners.full.json — never in this repo.
 * A business's own contact details are kept off every public surface (founder
 * decision 2026-11-06), and a public git history is the most public surface
 * there is. Quote source_url is blank for the same reason: it pointed at the
 * company's own website.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'db', 'first-partners.json');
const OUT = path.join(ROOT, 'db', 'seed-first-partners.sql');

const q = (v) => (v === null || v === undefined) ? 'NULL'
  : typeof v === 'number' ? (Number.isFinite(v) ? String(v) : 'NULL')
  : "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => q(JSON.stringify(Array.isArray(a) ? a.map(String) : []));

function providerSql(p, now) {
  const cols = {
    id: q(p.id), slug: q(p.slug), name: q(p.name),
    tagline: q(p.tagline || ''), about: q(p.about || ''),
    brand_color: q(p.brand_color || '#1f2937'), logo_path: q(p.logo_path || ''), logo_bg: q(p.logo_bg || '#ffffff'),
    years_label: q(p.years_label || ''), owner_public_name: q(p.owner_public_name || ''), team_label: q(p.team_label || ''),
    service_area: q(p.service_area || ''), area_short: q(p.area_short || ''),
    regions: arr(p.regions), service_areas: arr(p.service_areas), services: arr(p.services), service_tags: arr(p.service_tags),
    claims: arr(p.claims), policies: arr(p.policies),
    pricing_text: q(p.pricing_text || ''), deals: arr(p.deals),
    price_label: q(p.price_label || 'Pricing'), price_value: q(p.price_value || 'Free estimate'), card_note: q(p.card_note || ''),
    rating: q(typeof p.rating === 'number' ? p.rating : null), review_count: q(typeof p.review_count === 'number' ? p.review_count : null),
    rating_source: q(p.rating_source || ''), rating_checked_on: q(p.rating_checked_on || ''),
    internal_phone: q(p.internal_phone || ''), internal_email: q(p.internal_email || ''), website_url: q(p.website_url || ''),
    internal_notes: q(p.internal_notes || ''),
    status: q('prospect'), listed: '0', sort_rank: q(p.sort_rank || 1000),
    created_at: q(now), updated_at: q(now)
  };
  return 'INSERT OR IGNORE INTO providers (' + Object.keys(cols).join(', ') + ')\n  VALUES (' +
    Object.values(cols).join(', ') + ');';
}

function main() {
  const rows = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  const now = new Date().toISOString();
  const seen = new Set();
  const out = ['-- GENERATED by scripts/seed-partners.js from db/first-partners.json. Edit the JSON, not this file.', ''];
  for (const p of rows) {
    if (!/^PRV-\d{4}$/.test(p.id)) throw new Error('bad provider id: ' + p.id);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(p.slug)) throw new Error('bad slug: ' + p.slug);
    if (seen.has(p.slug)) throw new Error('duplicate slug: ' + p.slug);
    seen.add(p.slug);
    for (const a of p.service_areas || []) {
      if (!/^[a-z]+(-[a-z]+)*$/.test(a) && !/^\d{5}$/.test(a)) throw new Error('bad service area for ' + p.slug + ': ' + a);
    }
    out.push(providerSql(p, now));
    /* Rows seeded before migration 0002 have service_areas = '[]'. Fill those
       once; a list already edited in D1 is never overwritten. */
    out.push('UPDATE providers SET service_areas = ' + arr(p.service_areas) +
      ' WHERE id = ' + q(p.id) + " AND service_areas = '[]';");
    /* Photos and quotes are keyed to a provider that may already have been
       edited; they are only inserted when that provider has none yet, so a
       re-run cannot duplicate them. */
    (p.photos || []).forEach((ph, i) => out.push(
      'INSERT INTO provider_photos (provider_id, path, caption, sort) SELECT ' +
      [q(p.id), q(ph.path), q(ph.caption || ''), q(i)].join(', ') +
      ' WHERE NOT EXISTS (SELECT 1 FROM provider_photos WHERE provider_id = ' + q(p.id) + ' AND path = ' + q(ph.path) + ');'));
    (p.quotes || []).forEach((r, i) => out.push(
      'INSERT INTO provider_quotes (provider_id, quote, author, source, source_url, sort) SELECT ' +
      [q(p.id), q(r.quote), q(r.author || ''), q(r.source || ''), q(r.source_url || ''), q(i)].join(', ') +
      ' WHERE NOT EXISTS (SELECT 1 FROM provider_quotes WHERE provider_id = ' + q(p.id) + ' AND quote = ' + q(r.quote) + ');'));
    out.push('');
  }
  fs.writeFileSync(OUT, out.join('\n'));
  console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + rows.length + ' providers, all unlisted');
}

if (require.main === module) main();
module.exports = { providerSql };
