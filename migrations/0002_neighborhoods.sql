-- 0002: where companies work (founder spec 2026-11-07, design/serve/HOME_SPEC.md §3).
--
-- neighborhoods: towns, plus Boston/Cambridge/Somerville neighborhoods and
-- squares. region is the directory's fallback when no company names the place
-- itself; parent lets "Back Bay" find a company that serves "Boston".
-- popular_rank orders the "Popular areas" dropdown (NULL = not listed there).
-- neighborhood_zips: one row per ZIP. Any other 021xx ZIP falls back to Boston
-- in the page script.
-- providers.service_areas: JSON array of the neighborhood slugs (and, if a
-- company works by ZIP, ZIPs) it serves. Filled for the seeded companies by
-- db/seed-first-partners.sql, only where it is still '[]'.
--
-- The data rows live here rather than in a seed because the page expects them
-- to exist. Later changes are UPDATEs in D1, deliberately.

ALTER TABLE providers ADD COLUMN service_areas TEXT NOT NULL DEFAULT '[]';

CREATE TABLE neighborhoods (
  slug         TEXT PRIMARY KEY CHECK (slug GLOB '[a-z]*' AND slug NOT GLOB '*[^a-z-]*'),
  name         TEXT NOT NULL,
  region       TEXT NOT NULL CHECK (region IN ('core', 'north', 'west', 'south')),
  parent       TEXT REFERENCES neighborhoods(slug),
  popular_rank INTEGER
);

CREATE TABLE neighborhood_zips (
  zip          TEXT PRIMARY KEY CHECK (length(zip) = 5 AND zip NOT GLOB '*[^0-9]*'),
  neighborhood TEXT NOT NULL REFERENCES neighborhoods(slug)
);
CREATE INDEX idx_neighborhood_zips_neighborhood ON neighborhood_zips(neighborhood);

